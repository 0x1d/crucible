import type { JsonSchema, ServiceInfo } from "./registry";

/** Storage path of the generated declarations, beside the components that use them. */
export const SERVICE_TYPES_PATH = "components/services.d.ts";

function literal(value: unknown): string {
  return value === null || ["string", "number", "boolean"].includes(typeof value) ? JSON.stringify(value) : "unknown";
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function wrap(type: string): string {
  return /[|&]/.test(type) ? `(${type})` : type;
}

/** TypeScript type for a JSON Schema (the subset the gateway validates). */
export function schemaToType(schema: JsonSchema | undefined, indent = ""): string {
  if (schema === undefined || schema === true) return "unknown";
  if (schema === false) return "never";
  const s = schema as Record<string, unknown>;
  const inner = `${indent}  `;

  if ("const" in s) return literal(s.const);
  if (Array.isArray(s.enum)) return s.enum.map(literal).join(" | ") || "never";
  if (Array.isArray(s.anyOf) || Array.isArray(s.oneOf)) {
    const options = (s.anyOf ?? s.oneOf) as JsonSchema[];
    return options.map((option) => wrap(schemaToType(option, indent))).join(" | ") || "never";
  }
  if (Array.isArray(s.allOf)) {
    return (s.allOf as JsonSchema[]).map((part) => wrap(schemaToType(part, indent))).join(" & ") || "unknown";
  }

  const types = Array.isArray(s.type) ? (s.type as string[]) : typeof s.type === "string" ? [s.type] : [];
  if (types.length === 0) {
    if (s.properties) return objectType(s, indent, inner);
    if (s.items) return arrayType(s, indent);
    return "unknown";
  }
  return types
    .map((type) => {
      switch (type) {
        case "string":
          return "string";
        case "number":
        case "integer":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array":
          return arrayType(s, indent);
        case "object":
          return objectType(s, indent, inner);
        default:
          return "unknown";
      }
    })
    .join(" | ");
}

function arrayType(s: Record<string, unknown>, indent: string): string {
  return `Array<${schemaToType(s.items as JsonSchema | undefined, indent)}>`;
}

function objectType(s: Record<string, unknown>, indent: string, inner: string): string {
  const props = (s.properties ?? {}) as Record<string, JsonSchema>;
  const required = new Set(Array.isArray(s.required) ? (s.required as string[]) : []);
  const lines = Object.entries(props).map(
    ([name, sub]) => `${inner}${key(name)}${required.has(name) ? "" : "?"}: ${schemaToType(sub, inner)};`,
  );
  const extra = s.additionalProperties;
  if (extra !== false && !(extra === undefined && lines.length > 0)) {
    lines.push(`${inner}[key: string]: ${extra && extra !== true ? schemaToType(extra as JsonSchema, inner) : "unknown"};`);
  }
  return lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "Record<string, never>";
}

/** Declarations for `@nshde/services`, one entry per service with schemas. */
export function serviceDeclarations(services: ServiceInfo[]): string {
  const entries = services
    .filter((service) => service.valid)
    .map(
      (service) =>
        `    ${JSON.stringify(service.slug)}: {\n` +
        `      input: ${schemaToType(service.inputSchema, "      ")};\n` +
        `      output: ${schemaToType(service.outputSchema, "      ")};\n` +
        `    };`,
    );
  return `// Generated by nshde from the service schemas. Do not edit.
declare module "@nshde/services" {
  export interface Services {
${entries.join("\n")}
  }
  export type ServiceName = keyof Services;
  export function call<K extends ServiceName>(slug: K, args: Services[K]["input"]): Promise<Services[K]["output"]>;
  export function useService<K extends ServiceName>(
    slug: K,
    args: Services[K]["input"],
  ): { data: Services[K]["output"] | undefined; error: string | undefined; loading: boolean; reload: () => void };
}
`;
}
