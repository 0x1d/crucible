#!/usr/bin/env bash
# Generates firmware/components/homunculus_avatar/src/font8x16.inc (ASCII 32..126, 8x16 monochrome,
# one byte per row, MSB = leftmost pixel) from DejaVu Sans Mono Bold with ImageMagick.
# Usage: tools/gen-font.sh /path/to/DejaVuSansMono-Bold.ttf
set -euo pipefail
font="${1:?font file}"
out="$(cd "$(dirname "$0")/.." && pwd)/firmware/components/homunculus_avatar/src/font8x16.inc"
{
  echo "// Generated by tools/gen-font.sh from DejaVu Sans Mono Bold (Bitstream Vera licence). ASCII 32..126, 8x16."
  for c in $(seq 32 126); do
    ch=$(printf "\\$(printf '%03o' "$c")")
    magick -size 8x16 xc:black +antialias -font "$font" -pointsize 13 -fill white -gravity center \
      -annotate +0+0 "$ch" -depth 1 txt:- | tail -n +2 | awk -v c="$c" '
        { split($1, a, ","); y = a[2] + 0; sub(":", "", a[2]); x = a[1] + 0
          white = ($3 ~ /#FFFFFF|white/) ? 1 : 0
          row[y] = row[y] "" white }
        END { printf "    {"; for (y = 0; y < 16; y++) { v = 0; for (x = 1; x <= 8; x++) v = v * 2 + substr(row[y], x, 1); printf "0x%02X%s", v, y < 15 ? "," : "" } printf "},  // %d\n", c }'
  done
} > "$out"
